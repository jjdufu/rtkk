//! Compile-time static asset bundler for `web/dist/` with `Gzip` pre-compression and `SHA256` `ETag`s.

use flate2::Compression;
use flate2::write::GzEncoder;
use sha2::{Digest, Sha256};
use std::fmt::Write as _;
use std::io::Write as _;
use std::path::{Path, PathBuf};

const FALLBACK_INDEX_HTML: &str = concat!(
    "<!doctype html><html lang=\"zh-CN\"><head><meta charset=\"utf-8\">",
    "<meta name=\"viewport\" content=\"width=device-width,initial-scale=1\">",
    "<title>RTKK Console</title></head><body>",
    "<div id=\"root\">RTKK Daemon Ready</div></body></html>"
);

struct BundledAsset {
    url_path: String,
    mime: &'static str,
    etag: String,
    immutable: bool,
    raw_bytes: Vec<u8>,
    gzip_bytes: Vec<u8>,
}

fn guess_mime(path: &Path) -> &'static str {
    match path.extension().and_then(|e| e.to_str()).unwrap_or("") {
        "html" => "text/html; charset=utf-8",
        "js" | "mjs" => "application/javascript; charset=utf-8",
        "css" => "text/css; charset=utf-8",
        "svg" => "image/svg+xml",
        "json" | "map" => "application/json; charset=utf-8",
        "png" => "image/png",
        "ico" => "image/x-icon",
        "woff2" => "font/woff2",
        "txt" => "text/plain; charset=utf-8",
        _ => "application/octet-stream",
    }
}

fn compress_gzip(raw: &[u8]) -> Result<Vec<u8>, String> {
    let mut encoder = GzEncoder::new(Vec::new(), Compression::best());
    encoder
        .write_all(raw)
        .map_err(|e| format!("gzip write failed: {e}"))?;
    encoder
        .finish()
        .map_err(|e| format!("gzip finish failed: {e}"))
}

fn compute_etag(raw: &[u8]) -> String {
    let mut hasher = Sha256::new();
    hasher.update(raw);
    format!("\"{:x}\"", hasher.finalize())
}

fn collect_files_recursive(
    root: &Path,
    current: &Path,
    out: &mut Vec<PathBuf>,
) -> Result<(), String> {
    let entries = std::fs::read_dir(current)
        .map_err(|e| format!("failed to read directory {}: {e}", current.display()))?;
    let mut paths: Vec<PathBuf> = Vec::new();
    for entry_res in entries {
        let entry = entry_res.map_err(|e| format!("dir entry error: {e}"))?;
        paths.push(entry.path());
    }
    paths.sort();
    for p in paths {
        if p.is_dir() {
            collect_files_recursive(root, &p, out)?;
        } else if p.is_file() {
            let _ = p
                .strip_prefix(root)
                .map_err(|e| format!("strip_prefix failed: {e}"))?;
            out.push(p);
        }
    }
    Ok(())
}

fn build_asset_record(
    url_path: String,
    mime: &'static str,
    raw_bytes: Vec<u8>,
) -> Result<BundledAsset, String> {
    let etag = compute_etag(&raw_bytes);
    let gzip_bytes = compress_gzip(&raw_bytes)?;
    let immutable = url_path.starts_with("/assets/");
    Ok(BundledAsset {
        url_path,
        mime,
        etag,
        immutable,
        raw_bytes,
        gzip_bytes,
    })
}

fn format_byte_slice(bytes: &[u8]) -> String {
    let mut out = String::with_capacity(bytes.len().saturating_mul(4).saturating_add(4));
    out.push_str("&[");
    for (idx, b) in bytes.iter().enumerate() {
        if idx > 0 {
            out.push(',');
        }
        let _ = write!(out, "{b}");
    }
    out.push(']');
    out
}

fn generate_assets_module(dist_dir: &Path) -> Result<String, String> {
    let index_file = dist_dir.join("index.html");
    let (built, assets) = if index_file.is_file() {
        let mut files = Vec::new();
        collect_files_recursive(dist_dir, dist_dir, &mut files)?;
        let mut list = Vec::with_capacity(files.len());
        for file_path in files {
            let rel = file_path
                .strip_prefix(dist_dir)
                .map_err(|e| format!("strip_prefix error: {e}"))?;
            let rel_slash = rel.to_string_lossy().replace('\\', "/");
            let url_path = format!("/{rel_slash}");
            let raw = std::fs::read(&file_path)
                .map_err(|e| format!("failed to read {}: {e}", file_path.display()))?;
            let mime = guess_mime(&file_path);
            list.push(build_asset_record(url_path, mime, raw)?);
        }
        (true, list)
    } else {
        let fallback = build_asset_record(
            "/index.html".to_string(),
            "text/html; charset=utf-8",
            FALLBACK_INDEX_HTML.as_bytes().to_vec(),
        )?;
        (false, vec![fallback])
    };

    let mut code = String::new();
    let _ = writeln!(
        code,
        "/// Whether `web/dist/index.html` was present at compile time."
    );
    let _ = writeln!(code, "pub const WEB_DIST_BUILT: bool = {built};");
    let _ = writeln!(
        code,
        "/// Pre-compressed embedded frontend asset table generated by `build.rs`."
    );
    let _ = writeln!(
        code,
        "pub static EMBEDDED_WEB_ASSETS: &[EmbeddedAsset] = &["
    );
    for item in &assets {
        let raw_lit = format_byte_slice(&item.raw_bytes);
        let gz_lit = format_byte_slice(&item.gzip_bytes);
        let _ = writeln!(
            code,
            "    EmbeddedAsset {{ path: {:?}, mime: {:?}, etag: {:?}, immutable: {}, raw: {}, gzip: {} }},",
            item.url_path, item.mime, item.etag, item.immutable, raw_lit, gz_lit
        );
    }
    let _ = writeln!(code, "];");
    Ok(code)
}

fn main() -> Result<(), Box<dyn std::error::Error>> {
    println!("cargo:rerun-if-changed=web/dist");
    let manifest_dir = std::env::var("CARGO_MANIFEST_DIR")?;
    let out_dir = std::env::var("OUT_DIR")?;
    let dist_dir = Path::new(&manifest_dir).join("web").join("dist");
    let generated = generate_assets_module(&dist_dir)?;
    let dest_path = Path::new(&out_dir).join("embedded_web_assets.rs");
    std::fs::write(dest_path, generated)?;
    Ok(())
}
